"""Перевод температуры между шкалами Цельсия и Фаренгейта."""


def c_to_f(celsius):
    """Градусы Цельсия -> Фаренгейта (округление до 0,01)."""
    return round(celsius * 9 / 5 + 32, 2)


def f_to_c(fahrenheit):
    """Градусы Фаренгейта -> Цельсия (округление до 0,01)."""
    return round((fahrenheit - 32) * 5 / 9, 2)
